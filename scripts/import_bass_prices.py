def import_prices():
    """
    批量导入鲈鱼塘口价数据
    """
    prices_data = []
    
    for date_str, market, price, spec in BASS_PRICES:
        market_id = MARKET_IDS.get(market)
        if not market_id:
            print(f"警告: 找不到市场 '{market}' 的ID，跳过")
            continue
        
        prices_data.append({
            "fish_id": FISH_ID,
            "market_id": market_id,
            "price": price,
            "ts": date_str,
            "currency": "CNY",
            "unit": "kg",
            "price_type": "pond",  # 塘口价
            "source_url": f"水产养殖网行情周报 - {market} - {spec}"
        })
    
    print(f"准备导入 {len(prices_data)} 条鲈鱼塘口价数据...")
    
    # 批量导入
    response = requests.post(
        f"{API_BASE}/api/prices/batch",
        json={"prices": prices_data}
    )
    
    if response.status_code == 200:
        result = response.json()
        print(f"导入完成: 成功 {result.get('added', 0)} 条, 失败 {result.get('failed', 0)} 条")
        return result
    else:
        print(f"导入失败: {response.status_code} - {response.text}")
        return None


